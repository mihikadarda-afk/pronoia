const purposes: Record<Lang, Record<string, string>> = {
  en: {},
  hi: { 'Blood pressure': 'ब्लड प्रेशर', Diabetes: 'शुगर', Vitamin: 'विटामिन' },
  gu: { 'Blood pressure': 'બ્લડ પ્રેશર', Diabetes: 'ડાયાબિટીસ', Vitamin: 'વિટામિન' },
};

export function useT(): Strings & { purpose: (p: string) => string; lang: Lang } {
  const { lang } = useSession();
  return { ...(strings[lang] as Strings), purpose: (p) => purposes[lang][p] ?? p, lang };
}

